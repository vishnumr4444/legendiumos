async def decompose(command: str, context: str = "") -> dict:
    if config.OPENAI_API_KEY:
        try:
            return await _decompose_llm(command, context)
        except Exception as e:  # graceful fallback
            plan = _decompose_local(command)
            plan["engine"] = f"local-fallback ({type(e).__name__})"
            return plan
    plan = _decompose_local(command)
    plan["engine"] = "local"
    return plan


async def _decompose_llm(command: str, context: str) -> dict:
    user_msg = command if not context else f"{command}\n\nRelevant knowledge base context:\n{context}"
    async with httpx.AsyncClient(timeout=90) as client:
        r = await client.post(
            f"{config.OPENAI_BASE_URL}/chat/completions",
            headers={"Authorization": f"Bearer {config.OPENAI_API_KEY}"},
            json={
                "model": config.OPENAI_MODEL,
                "response_format": {"type": "json_object"},
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_msg},
                ],
            },
        )
        r.raise_for_status()
        plan = json.loads(r.json()["choices"][0]["message"]["content"])
        plan["engine"] = config.OPENAI_MODEL
        return plan


