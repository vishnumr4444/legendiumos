# ------------------------------------------------------------ comment analysis

RISK_KEYWORDS = {
    "blocker": ["blocked", "blocker", "can't proceed", "cannot proceed", "stuck", "waiting on"],
    "risk": ["risk", "might slip", "delay", "behind schedule", "concern", "issue"],
    "dependency": ["depends on", "dependency", "needs", "after", "requires"],
    "urgent": ["urgent", "asap", "immediately", "critical", "today"],
}


def analyze_comment(body: str) -> list[str]:
    low = body.lower()
    return [flag for flag, kws in RISK_KEYWORDS.items() if any(k in low for k in kws)]
