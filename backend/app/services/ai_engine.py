def _t(title, discipline, owner, est, subtasks=None):
    return {"title": title, "discipline": discipline, "owner": owner,
            "estimate_hours": est, "subtasks": subtasks or []}


def _decompose_local(command: str) -> dict:
    c = command.lower()
    robotics = any(k in c for k in ["nano", "otto", "ninja", "megapath", "project k",
                                    "pcb", "robot", "manufactur", "assembly"])
    ops = any(k in c for k in ["flipkart", "amazon", "listing", "logistics",
                               "procure", "packag", "marketing campaign"])
    chapter = "chapter" in c
    website = "website" in c or "web release" in c

    if chapter or (not robotics and not ops):
        return _plan_chapter(command, include_listing=("flipkart" in c or "amazon" in c),
                             include_site=website, include_nano=("nano" in c))
    if robotics:
        return _plan_robot_launch(command)
    return _plan_listing(command)


